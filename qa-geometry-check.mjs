import { check, done } from './qa-helpers.mjs';
import { resample, polylineLength, flattenBezier, splitBezier, rdpClosed, marchingSquares, polar, bbox } from './lib/geometry.ts';
console.log('Geometry');
const sq = [[0, 0], [100, 0], [100, 100], [0, 100], [0, 0]];
const r = resample(sq, 40, true);
check('closed resample gives the requested count', r.length === 40);
check('closed resample spacing is even', Math.abs(Math.hypot(r[1][0] - r[0][0], r[1][1] - r[0][1]) - 10) < 0.01);
check('polylineLength of a square is 400', Math.abs(polylineLength(sq) - 400) < 1e-9);
const a = [{ x: 0, y: 0, ix: 0, iy: 0, ox: 30, oy: 0 }, { x: 100, y: 0, ix: -30, iy: 0, ox: 0, oy: 0 }];
const flat = flattenBezier(a, false);
check('bezier flattening ends on the last anchor', flat[flat.length - 1][0] === 100);
const before = flattenBezier(a, false)[8];
splitBezier(a, 0, 0.5);
check('split adds one anchor', a.length === 3);
const after = flattenBezier(a, false);
const nearest = Math.min(...after.map(p => Math.hypot(p[0] - before[0], p[1] - before[1])));
check('split keeps the curve shape', nearest < 0.5, 'distance ' + nearest.toFixed(3));
const W = 60, H = 60, m = new Uint8Array(W * H);
for (let y = 10; y < 40; y++) for (let x = 10; x < 40; x++) m[y * W + x] = (x >= 20 && x < 30 && y >= 20 && y < 30) ? 0 : 1;
const loops = marchingSquares(m, W, H);
check('marching squares finds the outline and the hole', loops.length === 2);
check('a square outline simplifies to 4 corners', rdpClosed(loops[0], 1.1).length === 4);
check('polar: straight up is 0 degrees', Math.abs(polar({ x: 0, y: -50 }, { x: 0, y: 0 }).angle) < 1e-9);
check('polar: right is 90 degrees, radius in cm', Math.abs(polar({ x: 100, y: 0 }, { x: 0, y: 0 }).angle - 90) < 1e-9 && Math.abs(polar({ x: 100, y: 0 }, { x: 0, y: 0 }).radius - 10) < 1e-9);
check('bbox centre', bbox([[0, 0], [10, 20]]).cy === 10);
done('Geometry QA');
