import { readFileSync } from 'node:fs';
import { check, done } from './qa-helpers.mjs';
import { generateNails, expandStrokes } from './services/nails.ts';
console.log('Nails');
const doc = JSON.parse(readFileSync(new URL('./qa-sample-design.json', import.meta.url), 'utf8'));
const board = { W: doc.W, H: doc.H };
const { nails, groups } = generateNails(doc.strokes, 10, board);
check('every stroke becomes a group', groups.length === 2);
check('a 100 mm square at 10 mm spacing has 40 nails', groups[0].ids.length === 40);
check('square corners are nails', [[100, 100], [200, 100], [200, 200], [100, 200]].every(c => nails.some(n => n.x === c[0] && n.y === c[1])));
const coarse = generateNails(doc.strokes, 20, board);
check('wider spacing gives fewer nails', coarse.nails.length < nails.length);
const hidden = generateNails(doc.strokes.map((s, i) => i === 0 ? { ...s, h: true } : s), 10, board);
check('hidden shapes get no nails', hidden.groups.length === 1);
const bez = { type: 'bez', pts: [{ x: 250, y: 100, ix: 0, iy: 0, ox: 30, oy: 0 }, { x: 330, y: 100, ix: -30, iy: 0, ox: 0, oy: 0 }], closed: false, curve: true, c: '#fff', sym: 6, mir: true };
check('mandala symmetry makes 12 copies', expandStrokes([bez], board).length === 12);
const overlap = generateNails([{ type: 'line', pts: [[0, 0], [100, 0]], closed: false, curve: false, c: '#fff' }, { type: 'line', pts: [[0, 0], [0, 100]], closed: false, curve: false, c: '#fff' }], 10, board);
check('nails where shapes touch are shared', overlap.nails.length === 21);
done('Nails QA');
